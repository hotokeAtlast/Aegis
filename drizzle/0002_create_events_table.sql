CREATE TABLE events (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  planner_name TEXT NOT NULL,
  title TEXT NOT NULL,
  event_type TEXT NOT NULL,
  event_date TEXT NOT NULL,
  city TEXT NOT NULL,
  guest_count INTEGER NOT NULL,
  budget_min_inr INTEGER NOT NULL,
  budget_max_inr INTEGER NOT NULL,
  venue_pref TEXT NOT NULL,
  needs_parking INTEGER NOT NULL,
  expected_cars INTEGER NOT NULL DEFAULT 0,
  area_preference TEXT,
  food_type TEXT NOT NULL,
  veg_percent INTEGER NOT NULL DEFAULT 100,
  desserts INTEGER NOT NULL,
  fruits INTEGER NOT NULL,
  dry_fruits INTEGER NOT NULL,
  dietary_notes TEXT,
  entertainment_types TEXT NOT NULL DEFAULT '',
  entertainment_hours INTEGER NOT NULL DEFAULT 3,
  kids_activities INTEGER NOT NULL DEFAULT 0,
  decor_level TEXT NOT NULL DEFAULT 'simple',
  manpower_json TEXT NOT NULL DEFAULT '[]',
  budget_lines_json TEXT NOT NULL DEFAULT '[]',
  cost_per_plate_inr INTEGER NOT NULL DEFAULT 0,
  created_at INTEGER NOT NULL
);
